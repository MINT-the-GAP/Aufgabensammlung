const fs = require('node:fs')
const path = require('node:path')
const assembler = require('../assets/course-source.js')
const generator = require('../assets/course-generator.js')
const { buildSachsenCurriculum } = require('./sachsen-curriculum.cjs')

const root = path.resolve(__dirname, '..')
const projectFile = path.join(root, 'project.yml')
const curriculumFile = path.join(root, 'Lehrplan.md')
const jsonFile = path.join(root, 'assets', 'course-catalog.json')
const scriptFile = path.join(root, 'assets', 'course-catalog.js')
const checkOnly = process.argv.includes('--check')

function localTask(url) {
  const parsed = new URL(url)
  const match = decodeURIComponent(parsed.pathname).match(
    /^\/MINT-the-GAP\/Aufgabensammlung\/(?:refs\/heads\/)?main\/(.+)$/
  )
  if (!match) throw new Error('Unbekannte Aufgabenquelle: ' + url)
  const relative = match[1].replace(/\//g, path.sep)
  const absolute = path.resolve(root, relative)
  if (!absolute.startsWith(root + path.sep)) throw new Error('Aufgabenquelle verlässt das Repository: ' + url)
  if (!fs.existsSync(absolute)) throw new Error('Aufgabendatei fehlt: ' + relative)
  return { absolute, relative: match[1] }
}

function metadataValue(header, name) {
  const lines = String(header || '').replace(/\r\n?/g, '\n').split('\n')
  const pattern = new RegExp('^\\s*' + name + '\\s*:\\s*(.*)$', 'i')
  for (let index = 0; index < lines.length; index++) {
    const match = lines[index].match(pattern)
    if (!match) continue
    const parts = [match[1]]
    while (index + 1 < lines.length && /^[ \t]+\S/.test(lines[index + 1])) {
      parts.push(lines[++index].trim())
    }
    return parts.join(' ').trim()
  }
  return ''
}

function titleOf(body, relative) {
  const match = String(body || '').match(/^#\s+(.+?)\s*$/m)
  return match ? match[1].replace(/<[^>]+>/g, '').trim() : path.basename(relative, '.md')
}

function buildCatalog() {
  const yaml = fs.readFileSync(projectFile, 'utf8')
  const urls = Array.from(yaml.matchAll(/^\s*-\s+url:\s*(\S+)\s*$/gm), match => match[1])
    .filter(url => /\/Aufgabe_[^/]+\.md$/i.test(url))
  const seen = new Set()
  const tasks = []
  urls.forEach(function (url) {
    if (seen.has(url)) return
    seen.add(url)
    const file = localTask(url)
    const source = fs.readFileSync(file.absolute, 'utf8')
    const document = assembler.split(source)
    const rawTags = metadataValue(document.header, 'tags')
      .split(/[,;]|\s+-\s+/)
      .map(value => value.trim())
      .filter(Boolean)
    const classified = generator.classifyTags(rawTags)
    tasks.push({
      id: file.relative,
      url,
      title: titleOf(document.body, file.relative),
      tags: classified.tags,
      topics: classified.topics,
      difficulty: classified.difficulty,
      network: classified.network,
      operator: classified.operator,
    })
  })
  const catalog = {
    schema: generator.catalogSchema,
    version: generator.catalogVersion,
    source: {
      repository: 'https://github.com/MINT-the-GAP/Aufgabensammlung',
      ref: 'main',
      project: 'project.yml',
      curriculum: 'Lehrplan.md',
    },
    curriculum: buildSachsenCurriculum(curriculumFile),
    tasks,
  }
  return generator.validateCatalog(catalog)
}

function outputs(catalog) {
  const json = JSON.stringify(catalog, null, 2) + '\n'
  const script = [
    '/* Generated by scripts/build-course-catalog.cjs; do not edit manually. */',
    '(function (root, factory) {',
    '  const catalog = factory()',
    '  if (typeof module === \'object\' && module.exports) module.exports = catalog',
    '  if (root) root.SchulLiaCourseCatalog = catalog',
    '})(typeof window === \'object\' ? window : typeof globalThis === \'object\' ? globalThis : this, function () {',
    '  \'use strict\'',
    '  const catalog = ' + JSON.stringify(catalog),
    '  function freeze(value) {',
    '    if (!value || typeof value !== \'object\' || Object.isFrozen(value)) return value',
    '    Object.keys(value).forEach(function (key) { freeze(value[key]) })',
    '    return Object.freeze(value)',
    '  }',
    '  return freeze(catalog)',
    '})',
    '',
  ].join('\n')
  return { json, script }
}

function writeOrCheck(file, content) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
  if (current === content) return
  if (checkOnly) {
    throw new Error(path.relative(root, file) +
      ' ist nicht aktuell. Führe node scripts/build-course-catalog.cjs aus.')
  }
  fs.writeFileSync(file, content, 'utf8')
}

const catalog = buildCatalog()
const rendered = outputs(catalog)
writeOrCheck(jsonFile, rendered.json)
writeOrCheck(scriptFile, rendered.script)
const complete = catalog.tasks.filter(task =>
  task.topics.length && task.difficulty !== null && task.network !== null && task.operator
).length
console.log('Kurskatalog: ' + catalog.tasks.length + ' Aufgaben, ' + complete + ' vollständig klassifiziert' +
  (checkOnly ? ' (aktuell).' : '.'))
